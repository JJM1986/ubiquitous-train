// Löst eine Rolle für ein System auf → {name, dim, weight, unit, kat}
export function resolvePart(systemId, roleKey) {
  const role = PART_ROLES[roleKey];
  const mapped = (PART_MAPPINGS[systemId] || {})[roleKey];
  const name = mapped?.name || role.rolle;
  return {
    name,
    dim: mapped?.dim || "—",
    weight: mapped?.weight ?? 0,
    unit: role.einh,
    kat: role.kat,
  };
}

// Gewicht nach Teilname (Rückwärtskompatibilität für geruestrechnerSession)
export function weightForName(systemId, roleKey) {
  const mapped = (PART_MAPPINGS[systemId] || {})[roleKey];
  return mapped?.weight ?? 0;
}

// Alle Katalogteile eines Systems (für Materialkatalog)
export function catalogForSystem(systemId) {
  return Object.keys(PART_ROLES).map((key) => {
    const part = resolvePart(systemId, key);
    return { role: key, ...part };
  });
}